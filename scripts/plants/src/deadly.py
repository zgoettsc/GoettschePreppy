# Deadly and seriously harmful plants and fungi of the United States, plus the dangerous
# look-alikes of foraged plants. Authored for GoettschePreppy by worker D2.
#
# risk:  lethal  = deaths recorded in people from eating it (or a part of it)
#        serious = hospital-level poisoning, but deaths rare or not recorded in the US
#        contact = harm from touching or burning it (rash, burns, blindness), not from eating
# Fields: key, sci (name as authored; build resolves to the PLANTS accepted name/symbol),
#         common (first is the display name), id (plain-word identification features),
#         harm (what it does and which parts), habitat, mistaken_for (text, may name things
#         not in this dataset), look (look-alike keys -> how to tell; the build makes links
#         two-way), src (source keys), notes.
# Fungi have no USDA PLANTS symbol; their range is set by hand in `states`/`range_note`.

D = []
def d(key, sci, common, risk, id, harm, habitat, mistaken_for='', look=None, src=None, kind='plant', **kw):
    D.append(dict(key=key, sci=sci, common=common, group='deadly', risk=risk, kind=kind, id=id, harm=harm,
                  habitat=habitat, mistaken_for=mistaken_for, look=look or {}, src=src or [], **kw))

